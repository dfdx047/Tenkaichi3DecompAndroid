/* s32 IVec4_InGsRange(IVec4 *p): 1 when 0 < p.x / 16 < 4096, 0 < p.y / 16 < 4096 and p.w > 0 (sticky zero / sign flags
 * of p - 0 on x, y, w and of 4096 - p on x, y), else 0. sceVu0ClipScreen with integer input and the result inverted. */
__asm__(
    ".text\n"
    ".align 3\n"
    ".globl IVec4_InGsRange\n"
    ".type IVec4_InGsRange, @function\n"
    ".set push\n"
    ".set noreorder\n"
    "IVec4_InGsRange:\n"
    "    lqc2 $vf7, 0x0($4)\n"
    "    vsub.xyzw $vf4, $vf0, $vf0\n"
    "    lui $8, (0x45800000 >> 16)\n"
    "    dsll $8, $8, 16\n"
    "    ori $8, $8, 0x4580\n"
    "    dsll $8, $8, 16\n"
    "    qmtc2 $8, $vf5\n"
    "    vitof4.xy $vf7, $vf7\n"
    "    vitof0.zw $vf7, $vf7\n"
    "    .word 0x48C08000 /* ctc2.ni $zero, $vi16 */\n"
    "    vsub.xyw $vf0, $vf7, $vf4\n"
    "    vsub.xy $vf0, $vf5, $vf7\n"
    "    vnop\n"
    "    vnop\n"
    "    vnop\n"
    "    vnop\n"
    "    vnop\n"
    "    .word 0x48428000 /* cfc2.ni $v0, $vi16 */\n"
    "    andi $2, $2, 0xC0\n"
    "    jr $31\n"
    "    sltiu $2, $2, 0x1\n"
    ".set pop\n"
    ".size IVec4_InGsRange, . - IVec4_InGsRange\n"
);

