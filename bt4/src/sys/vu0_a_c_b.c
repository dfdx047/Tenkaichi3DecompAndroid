/* angles = the pitch (x) and yaw (y) of the matrix's Z axis: Vec3_DirToEuler of (rows 0-2 of m, row 3 = (0,0,0,1))
 * times (0, 0, 1, 1), i.e. of row 2 with 1 added to its w. angles.z = 0. Compiled C with inline assembly. */
void Mtx_AxisZToEuler(Vec4 *angles, Mtx44 *m) {
    Mtx44 mt;
    Vec4 dir;

    __asm__ volatile(
        "lq $8, 0(%1)\n"
        "lq $9, 0x10(%1)\n"
        "lq $10, 0x20(%1)\n"
        "sq $8, 0(%0)\n"
        "sq $9, 0x10(%0)\n"
        "sq $10, 0x20(%0)\n"
        "sqc2 $vf0, 0x30(%0)\n"
        : : "r"(&mt), "r"(m) : "$8", "$9", "$10");
    Mtx_MulVec4(&dir, &mt, &gVu0AxisZW);
    Vec3_DirToEuler(angles, &dir);
}

