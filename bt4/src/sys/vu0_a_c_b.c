/* Vu0_SinCos: internal, non-standard call. In: angle in $f12. Out: vf12.x = sin, vf12.y = cos, vf12.z = vf12.w = +/-0.
 * Clobbers $v0, $t0, $t1, $f0, $f12, vf4-vf7, Q; callers keep $ra in $a2. u = angle < 0 ? pi/2 + angle : pi/2 - angle;
 * cos = u + c3 u^3 + c5 u^5 + c7 u^7 + c9 u^9; sin = +/- vsqrt(1 - cos * cos), negative when angle < 0.
 * Correct for |angle| <= pi only. (libvu0's _sceVu0ecossin.) */
__asm__(
    ".text\n"
    ".align 3\n"
    ".globl Vu0_SinCos\n"
    ".type Vu0_SinCos, @function\n"
    ".set push\n"
    ".set noreorder\n"
    "Vu0_SinCos:\n"
    "    lui $2, %hi(gVu0SinCoef)\n"
    "    addiu $2, $2, %lo(gVu0SinCoef)\n"
    "    mtc1 $0, $f0\n"
    "    c.lt.s $f12, $f0\n"
    "    lwc1 $f0, %gp_rel(gVu0HalfPi)($28)\n"
    "    bc1f 1f\n"
    "    nop\n"
    "    add.s $f12, $f0, $f12\n"
    "    j 2f\n"
    "    li $9, 1\n"
    "1:  sub.s $f12, $f0, $f12\n"
    "    move $9, $0\n"
    "2:  mfc1 $8, $f12\n"
    "    qmtc2 $8, $vf4\n"
    "    lqc2 $vf5, 0($2)\n"
    "    vmr32.w $vf4, $vf4\n"
    "    vaddx.x $vf12, $vf0, $vf4x\n"
    "    vmul.x $vf4, $vf4, $vf4\n"
    "    vmulx.yzw $vf12, $vf12, $vf0x\n"
    "    vmulw.xyzw $vf6, $vf5, $vf4w\n"
    "    vmulx.xyzw $vf6, $vf6, $vf4x\n"
    "    vmulx.xyz $vf6, $vf6, $vf4x\n"
    "    vaddw.x $vf12, $vf12, $vf6w\n"
    "    vmulx.xy $vf6, $vf6, $vf4x\n"
    "    vaddz.x $vf12, $vf12, $vf6z\n"
    "    vmulx.x $vf6, $vf6, $vf4x\n"
    "    vaddy.x $vf12, $vf12, $vf6y\n"
    "    vaddx.x $vf12, $vf12, $vf6x\n"
    "    vaddx.xy $vf12, $vf0, $vf12x\n"
    "    vmul.x $vf7, $vf12, $vf12\n"
    "    vsubx.w $vf7, $vf0, $vf7x\n"
    "    vsqrt $Q, $vf7w\n"
    "    vwaitq\n"
    "    bnez $9, 3f\n"
    "    vaddq.x $vf7, $vf0, $Q\n"
    "    b 4f\n"
    "    vaddx.x $vf12, $vf0, $vf7x\n"
    "3:  vsubx.x $vf12, $vf0, $vf7x\n"
    "4:  jr $31\n"
    "    nop\n"
    ".set pop\n"
    ".size Vu0_SinCos, . - Vu0_SinCos\n"
);

