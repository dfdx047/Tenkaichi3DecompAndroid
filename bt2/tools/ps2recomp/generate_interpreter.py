"""Handlers of the EE interpreter bridge (WHOLE_GAME_COVERAGE_PLAN.md, step 3).

The interpreter runs code no generated function holds. It decodes branches and jumps itself; every other
instruction runs through a handler made by the pinned recompiler from that exact instruction word, with
the same source preparation as the game's functions (prepare_runtime.prepare_text). So an instruction
means the same thing interpreted as compiled, and the generator's corrections apply to both.

The words are every distinct instruction word of the mapped code of all programs that is not a branch or
jump. They are laid out as a synthetic program of one-instruction functions at BASE, generated, prepared,
and each body becomes a handler whose program counter is a parameter. Output (ignored):
game/generated/ee-interpreter/ (handler units, the table and a CMake fragment) and the raw generation in
work/bt2-generation/interpreter/. A word the table lacks stops the interpreter by name.

    python tools/ps2recomp/generate_interpreter.py
"""
import csv, hashlib, json, re, subprocess, struct, sys
from pathlib import Path
import overlay_programs
from build_tools import recompiler
from prepare_runtime import prepare_text, detach_generated_headers, route_data_cache, VU_QUIET, VU_FLAG_SETTING
from map_gaps import program_view

ROOT = Path(__file__).resolve().parents[2]
FOLDER = ROOT / 'work/bt2-generation/interpreter'
OUTPUT = ROOT / 'game/generated/ee-interpreter'
BASE = 0x01000000
PER_UNIT = 2048


def is_control(word):
    """Branches and jumps, which the interpreter decodes itself: JR, JALR, J, JAL, the conditional and
    likely branches, REGIMM branches, and the COP0/COP1/COP2 condition branches."""
    op, rs, rt, fn = word >> 26, (word >> 21) & 31, (word >> 16) & 31, word & 63
    return ((op == 0 and fn in (8, 9)) or op in (2, 3, 4, 5, 6, 7, 20, 21, 22, 23)
            or (op == 1 and rt in (0, 1, 2, 3, 16, 17, 18, 19)) # REGIMM 24/25 are MTSAB/MTSAH
            or (op in (16, 17, 18) and rs == 8))


def census():
    """Sorted distinct non-control words of the mapped code of the main program and every overlay."""
    words = set()
    for name in ['main', *sorted(overlay_programs.PROGRAMS)]:
        rows, word, _, _, _ = program_view(name)
        for start, end in rows:
            for at in range(start, end, 4):
                value = word(at)
                if value is not None and not is_control(value):
                    words.add(value)
    return sorted(words)


def handler_body(source, address):
    """The statements of a generated one-instruction function at `address`, with its program counter
    as the parameter `pc`."""
    body = source[source.index('{', source.index(f'FUN_{address:08X}_0x{address:x}(')) + 1:source.rindex('}')]
    body = re.sub(r'#ifdef PS2_FUNCTION_LOG_TRACKER.*?#endif\n', '', body, flags=re.S)
    body = re.sub(r'^\s*//.*\n', '', body, flags=re.M) # The disassembly comments name the synthetic address.
    if 'switch (ctx->pc)' in body or 'goto ' in body or 'dispatchGuestBranch' in body:
        raise ValueError(f'Handler for 0x{address:08X} has control flow')
    body = re.sub(rf'0x0*{address + 4:x}u\b', '(pc + 4u)', body, flags=re.I)
    body = re.sub(rf'0x0*{address:x}u\b', 'pc', body, flags=re.I)
    if re.search(rf'0x0*({address:x}|{address + 4:x})\b', body, flags=re.I):
        raise ValueError(f'Handler for 0x{address:08X} names its address in another form')
    return body


# Handler flags (EeInterpreterHandler::flags). The VU0 status flags are reported to the runtime between a
# write of the status flag and its next read, as prepare_runtime.route_cop2_condition does in address
# order within a function; the interpreter applies the same rule in execution order.
WRITES_VU_STATUS, READS_VU_STATUS, SETS_VU_FLAGS, UNKNOWN_VU = 1, 2, 4, 8


def handler_flags(source, body):
    """The flags of a handler, from its raw source's disassembly comment and its prepared body."""
    flags = (WRITES_VU_STATUS if 'runtime->writeVuStatusFlag(' in body else 0) | (READS_VU_STATUS if 'runtime->readVuStatusFlag(' in body else 0)
    mnemonic = re.search(r'// 0x[0-9a-f]+: 0x[0-9a-f]+  ([a-z0-9.]+)', source)
    if mnemonic and mnemonic[1].startswith('v') and not mnemonic[1].startswith(VU_QUIET):
        flags |= SETS_VU_FLAGS if mnemonic[1].startswith(VU_FLAG_SETTING) else UNKNOWN_VU
    return flags


def render_unit(index, entries):
    """One handler unit: the handlers of `entries` [(word, body)] and their part of the table."""
    lines = ['// Generated by tools/ps2recomp/generate_interpreter.py; local and ignored.',
             '#include <stdexcept>', '#include "ps2_runtime_macros.h"', '#include "ps2_runtime.h"',
             '#include "ps2_syscalls.h"', '#include "ps2_stubs.h"', '#include "ee_interpreter_handlers.h"', '',
             'namespace {']
    for word, body, _ in entries:
        lines.append(f'void h_{word:08X}(uint8_t* rdram, R5900Context* ctx, PS2Runtime* runtime, uint32_t pc) {{'
                     f'(void)rdram;(void)runtime;(void)pc;{body}}}')
    lines += ['}', '', f'extern const EeInterpreterHandler ee_interpreter_handlers_{index:03}[] = {{']
    lines += [f'    {{0x{word:08X}u, h_{word:08X}, {flags}u}},' for word, _, flags in entries]
    lines += ['};', '']
    return '\n'.join(lines)


def render_table(counts):
    """The table unit: every unit's part, in word order (the parts are consecutive and sorted)."""
    lines = ['// Generated by tools/ps2recomp/generate_interpreter.py; local and ignored.',
             '#include "ee_interpreter_handlers.h"', '']
    lines += [f'extern const EeInterpreterHandler ee_interpreter_handlers_{n:03}[];' for n in range(len(counts))]
    lines += ['', 'const EeInterpreterHandlerPart ee_interpreter_handler_parts[] = {']
    lines += [f'    {{ee_interpreter_handlers_{n:03}, {count}u}},' for n, count in enumerate(counts)]
    lines += ['};', f'const unsigned ee_interpreter_handler_part_count = {len(counts)}u;', '']
    return '\n'.join(lines)


def main():
    import argparse
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--reuse', action='store_true', help='Reuse the raw generation when it was made from the same words.')
    args = parser.parse_args()
    words = census()
    FOLDER.mkdir(parents=True, exist_ok=True)
    raw = FOLDER / 'raw'
    image = b''.join(struct.pack('<I', word) for word in words)
    manifest_path = FOLDER / 'manifest.json'
    reuse = (args.reuse and manifest_path.exists()
             and json.loads(manifest_path.read_text(encoding='utf-8')).get('words_sha256') == hashlib.sha256(image).hexdigest())
    elf = overlay_programs.wrap(image, BASE, BASE)
    (FOLDER / 'handlers.elf').write_bytes(elf)
    with (FOLDER / 'handlers.csv').open('w', newline='', encoding='utf-8') as stream:
        out = csv.writer(stream)
        out.writerow(['Name', 'Start', 'End', 'Size'])
        for n in range(len(words)):
            address = BASE + n * 4
            out.writerow([f'FUN_{address:08X}', f'0x{address:08X}', f'0x{address + 4:08X}', 4])
    build = ROOT / 'build/ps2recomp-tools'
    tool = recompiler()
    provenance = json.loads((build / 'bt2-tool-provenance.json').read_text(encoding='utf-8'))
    if (provenance['lock_sha256'] != hashlib.sha256((ROOT / 'config/ps2recomp.lock.json').read_bytes()).hexdigest()
            or provenance['recompiler_sha256'] != hashlib.sha256(tool.read_bytes()).hexdigest()):
        raise SystemExit('Tool provenance does not match the lock file; rebuild with build_tools.py.')
    if not reuse:
        if raw.exists():
            for path in raw.iterdir():
                path.unlink()
        raw.mkdir(exist_ok=True)
        config = FOLDER / 'config.toml'
        config.write_text('[general]\n' + '\n'.join(f'{key} = {json.dumps(path.resolve().as_posix())}' for key, path in (
            ('input', FOLDER / 'handlers.elf'), ('ghidra_output', FOLDER / 'handlers.csv'), ('output', raw))) +
            '\nsingle_file_output = false\nlow_memory_mode = true\noutput_worker_threads = 1\n'
            'patch_syscalls = false\npatch_cop0 = false\npatch_cache = false\nstubs = []\nskip = []\nentry_points = []\n', encoding='utf-8')
        with (FOLDER / 'generation.log').open('w', encoding='utf-8') as log:
            subprocess.run([str(tool), str(config)], cwd=FOLDER, check=True, stdout=log, stderr=subprocess.STDOUT)
    entries = []
    for n, word in enumerate(words):
        address = BASE + n * 4
        name = f'FUN_{address:08X}_0x{address:x}'
        source = (raw / f'{name}.cpp').read_text(encoding='utf-8')
        text, _ = prepare_text(source, address)
        text, _ = route_data_cache(text)
        text = detach_generated_headers(text, name)
        body = handler_body(text, address)
        entries.append((word, body, handler_flags(source, body)))
    OUTPUT.mkdir(parents=True, exist_ok=True)
    files = {}
    counts = []
    for index in range(0, len(entries), PER_UNIT):
        part = entries[index:index + PER_UNIT]
        files[f'handlers_{index // PER_UNIT:03}.cpp'] = render_unit(index // PER_UNIT, part)
        counts.append(len(part))
    files['handler_table.cpp'] = render_table(counts)
    files['ee_interpreter.cmake'] = 'target_sources(bt2-entry-probe PRIVATE\n' + ''.join(
        f'    "${{CMAKE_CURRENT_SOURCE_DIR}}/game/generated/ee-interpreter/{name}"\n' for name in sorted(files) if name.endswith('.cpp')) + ')\n'
    # Unchanged files keep their timestamps, so a rebuild compiles only the units that changed.
    for stale in OUTPUT.iterdir():
        if stale.name not in files:
            stale.unlink()
    for name, text in files.items():
        path = OUTPUT / name
        if not path.exists() or path.read_text(encoding='utf-8') != text:
            path.write_text(text, encoding='utf-8')
    (FOLDER / 'manifest.json').write_text(json.dumps({
        'words': len(words), 'words_sha256': hashlib.sha256(image).hexdigest(), 'units': len(counts),
        'lock_sha256': provenance['lock_sha256'], 'recompiler_sha256': provenance['recompiler_sha256']}, indent=2) + '\n', encoding='utf-8')
    print(f'{len(words)} handlers in {len(counts)} units under {OUTPUT}; local and ignored.')


if __name__ == '__main__':
    sys.exit(main())
