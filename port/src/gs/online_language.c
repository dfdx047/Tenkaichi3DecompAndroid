const char *PortOnline_Text(const char *text){
    unsigned i;int english=Port_GameProfileEnglish();
    /* Isolated render checks can exercise both UI catalogs with one test disc.
     * Disc profiles, game data and normal player language selection are untouched. */
    if(getenv("BT4_RENDER_TEST")&&getenv("BT4_UI_LANGUAGE_TEST"))english=!strcmp(getenv("BT4_UI_LANGUAGE_TEST"),"en");
    if(!text||sRaw||english)return text;
    for(i=0;i<sizeof(kText)/sizeof(kText[0]);i++)if(!strcmp(text,kText[i][0]))return kText[i][1];
    return text;
}
