"""Disc-layout boundaries, unsafe archives, and generated Spanish text."""
import io
from pathlib import Path
import struct
import sys
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'port/tools'))
import import_native_disc as discs
import make_tag_text


class DiscLayouts(unittest.TestCase):
    def test_all_logical_ids_fit_their_own_disc(self):
        for region,counts,*_ in discs.PROFILES.values():
            for volume,count in enumerate(discs.COUNTS):
                actual=[discs.source_index(region,volume,i) for i in range(count)]
                self.assertGreaterEqual(min(actual),0)
                self.assertLess(max(actual),counts[volume])

    def test_europe_menu_story_character_boundaries(self):
        # First main-menu archive, first story bank, first battle table, last resource.
        for logical,physical in ((448,451),(509,512),(510,606),(657,753),(658,904),(3398,3644)):
            self.assertEqual(discs.source_index('eu',1,logical),physical)
        self.assertEqual(discs.source_index('eu',2,65200),65200)

    def test_japan_duplicate_language_banks(self):
        self.assertEqual(discs.source_index('jp',1,5),discs.source_index('jp',1,6))
        for i in range(1372):
            self.assertEqual(discs.source_index('jp',2,30000+i),discs.source_index('jp',2,31372+i))
        for i in range(56):
            self.assertEqual(discs.source_index('jp',2,65004+i),discs.source_index('jp',2,65060+i))
        self.assertEqual(discs.source_index('jp',2,65116),63688)
        self.assertEqual(discs.source_index('jp',2,65200),63772)

    def test_invalid_logical_ids(self):
        for volume,index in ((-1,0),(3,0),(1,-1),(1,3399)):
            with self.assertRaises(ValueError):discs.source_index('eu',volume,index)
        with self.assertRaises(ValueError):discs.source_index('unknown',1,0)

    def test_existing_import_is_never_overwritten(self):
        with tempfile.TemporaryDirectory() as directory:
            marker=Path(directory)/'keep.txt';marker.write_text('keep')
            with self.assertRaises(ValueError):discs.extract('missing.iso',directory)
            self.assertEqual(marker.read_text(),'keep')

    def test_archive_bounds_and_truncation(self):
        class Iso:
            def __init__(self,raw):self.raw=raw
            def get_record(self,**_):return type('Record',(),{'data_length':64})()
            def open_file_from_iso(self,**_):return io.BytesIO(self.raw)
        valid=b'AFS\0'+struct.pack('<III',1,16,48)
        self.assertEqual(discs.archive_table(Iso(valid),'archive',1),[(16,48)])
        for raw in (b'AFS\0',valid[:10],b'bad!'+valid[4:],b'AFS\0'+struct.pack('<III',1,15,4),
                    b'AFS\0'+struct.pack('<III',1,16,49)):
            with self.assertRaises(ValueError):discs.archive_table(Iso(raw),'archive',1)

    def test_spanish_placeholders_and_generated_catalog(self):
        rows=make_tag_text.catalog()  # rejects repeated keys and changed printf arguments
        self.assertEqual(rows['Random'],'Aleatorio')
        self.assertIn('ñ', ''.join(rows.values()))
        import json
        expected='/* Generated by port/tools/make_tag_text.py. Edit port/translations/tag/es.tsv. */\n'
        expected+=''.join('{'+json.dumps(en,ensure_ascii=False)+','+json.dumps(rows[en],ensure_ascii=False)+'},\n' for en in sorted(rows))
        self.assertEqual((ROOT/'port/src/gs/tag_text_es.inc').read_text(encoding='utf-8'),expected)


if __name__=='__main__':unittest.main()
