"""Import the mod's authored gauntlets into the native game, without game assets.

Pass the PCSX2 workspace as the argument. The generated records contain only
fighter IDs, equipment choices and the authors' wave names and rules.
"""
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[2]
workspace = Path(sys.argv[1])
sys.path.insert(0, str(workspace / 'bt3-multifighter/tools'))
import gauntlet_data as data

out = ['/* Generated by port/tools/import_tag_gauntlets.py. */']
entries = []
for game in ('bt3', 'bt4'):
    source = data.load(game, workspace / f'{game}-multifighter/gauntlets/gauntlets.json')
    if source['problems']:
        raise SystemExit(source['problems'])
    for index, gauntlet in enumerate(source['gauntlets']):
        waves = data.plan(gauntlet, source['potara'])
        symbol = f'gauntlet_{game}_{index}'
        out.append(f'static const TagWave {symbol}[] = {{')
        for wave in waves:
            enemies = []
            for fighter in wave['enemies']:
                items = fighter['items'] + [-1] * (8-len(fighter['items']))
                enemies.append('{%d,%d,{%s}}' % (fighter['character'], fighter['costume'], ','.join(map(str,items))))
            out.append('{%s,%d,%d,{%s}},' % (json.dumps(wave['label'], ensure_ascii=True), wave['difficulty'], len(enemies), ','.join(enemies)))
        out.append('};')
        entries.append('{%s,%d,%d,%d,%s}' % (json.dumps(gauntlet['title']),game=='bt4',len(waves), max(len(w['enemies']) for w in waves),symbol))
out.append('static const TagGauntlet gauntlets[] = {\n' + ',\n'.join(entries) + '\n};')
(root/'src/battle/tag_gauntlets.inc').write_text('\n'.join(out)+'\n', encoding='utf-8')
print(f'Imported {len(entries)} gauntlets.')
