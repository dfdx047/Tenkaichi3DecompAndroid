#!/usr/bin/env python3
"""Offline DXIL build. No shader compiler is required on the player's computer.

SPIRV_CROSS and DXC select build-only tools. Generated DXIL and source hashes are
committed together. Ordinary Windows builds reject stale generated shaders.
"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

NAMES = ('gs.vert', 'gs.frag', 'gsnz.frag', 'gswb.frag', 'vu0.vert',
         'vu4.vert', 'vu6.vert', 'fx.vert', 'outline.frag', 'alphakey.frag', 'dclut.frag',
         'avg.frag', 'grade.frag')

def inputs(root):
    folder = root / 'port/src/gs/shaders'
    return {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(folder.glob('*.*')) if p.suffix in ('.vert', '.frag')}

def prepare(root, gen, windows, generate=False):
    if not windows:
        return
    generated = root / 'port/src/gs/generated'
    header = generated / 'shaders_dxil.h'
    manifest = generated / 'shaders_dxil.json'
    if generate:
        cross = os.environ.get('SPIRV_CROSS') or shutil.which('spirv-cross')
        dxc = os.environ.get('DXC') or shutil.which('dxc')
        if not cross or not dxc:
            raise RuntimeError('DXIL generation needs SPIRV_CROSS and DXC build tools')
        generated.mkdir(parents=True, exist_ok=True)
        arrays, shaders = [], {}
        for name in NAMES:
            spv = gen / (name + '.spv')
            hlsl = gen / (name + '.hlsl')
            dxil = gen / (name + '.dxil')
            commands = [[cross, str(spv), '--hlsl', '--shader-model', '60', '--output', str(hlsl)],
                        [dxc, '-T', 'vs_6_0' if name.endswith('.vert') else 'ps_6_0',
                         '-E', 'main', '-O3', '-Ges', '-Qstrip_debug', '-Qstrip_reflect',
                         str(hlsl), '-Fo', str(dxil)]]
            for index, cmd in enumerate(commands):
                if index == 1:
                    # DXIL's conservative-depth validator requires an explicit
                    # non-perspective centroid/sample position. Rendering here is
                    # single-sample; do not change the colour/UV interpolants.
                    text = hlsl.read_text()
                    if 'SV_DepthLessEqual' in text or 'SV_DepthGreaterEqual' in text:
                        text = text.replace('float4 gl_FragCoord : SV_Position;',
                                            'noperspective centroid float4 gl_FragCoord : SV_Position;')
                        hlsl.write_text(text)
                r = subprocess.run(cmd, capture_output=True, text=True,
                                   **({'creationflags': 0x08000000} if os.name == 'nt' else {}))
                if r.returncode:
                    raise RuntimeError(name + ': ' + r.stdout + r.stderr)
            data = dxil.read_bytes()
            if data[:4] != b'DXBC':
                raise RuntimeError('Invalid compiled DXIL container: ' + name)
            stem, stage = name.split('.')
            symbol = 'k' + stem.capitalize() + stage.capitalize() + 'Dxil'
            arrays.append('static const unsigned char ' + symbol + '[] = {\n' +
                          '\n'.join(','.join(str(x) for x in data[i:i+24]) + ','
                                    for i in range(0, len(data), 24)) + '\n};\n')
            shaders[name] = {'spv_sha256': hashlib.sha256(spv.read_bytes()).hexdigest(),
                             'dxil_sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data)}
        header.write_text('/* Generated by port/tools/dx12_shaders.py. Do not edit. */\n' + ''.join(arrays))
        manifest.write_text(json.dumps({'source_sha256': inputs(root), 'shaders': shaders,
                                       'header_sha256': hashlib.sha256(header.read_bytes()).hexdigest()}, indent=2) + '\n')
    if not manifest.exists() or not header.exists():
        raise RuntimeError('Missing DXIL shaders. Run port/tools/dx12_shaders.py --generate')
    record = json.loads(manifest.read_text())
    if record['source_sha256'] != inputs(root) or record['header_sha256'] != hashlib.sha256(header.read_bytes()).hexdigest():
        raise RuntimeError('Stale DXIL shaders. Regenerate with port/tools/dx12_shaders.py --generate')
    for name, info in record['shaders'].items():
        if info['spv_sha256'] != hashlib.sha256((gen / (name + '.spv')).read_bytes()).hexdigest():
            raise RuntimeError('SPIR-V changed for ' + name + '; regenerate DXIL shaders')

if __name__ == '__main__':
    root = Path(__file__).resolve().parents[2]
    prepare(root, root / 'port/build/gen/gs', True, '--generate' in sys.argv)
    print('DXIL shaders generated and verified' if '--generate' in sys.argv else 'DXIL shader sources verified')
