#!/usr/bin/env python3
"""Build the native mod's Spanish and Portuguese lookups; reject changed printf arguments."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
FORMAT = re.compile(r'%(?:%|[-+#0]*\d*(?:\.\d+)?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcsp])')


def catalog(lang='es'):
    rows = {}
    for n, line in enumerate((ROOT / f'port/translations/tag/{lang}.tsv').read_text(encoding='utf-8').splitlines(), 1):
        if not line:
            continue
        en, es = line.split('\t')
        if not en or not es or en in rows:
            raise ValueError(f'Duplicate/empty translation at line {n}: {en}')
        if FORMAT.findall(en) != FORMAT.findall(es):
            raise ValueError(f'Format arguments changed at line {n}: {en}')
        rows[en] = es
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for lang, name in (('es', 'Spanish'), ('pt', 'Portuguese')):
        rows = catalog(lang)
        output = f'/* Generated by port/tools/make_tag_text.py. Edit port/translations/tag/{lang}.tsv. */\n'
        for en in sorted(rows):
            output += '{' + json.dumps(en, ensure_ascii=False) + ',' + json.dumps(rows[en], ensure_ascii=False) + '},\n'
        path = ROOT / f'port/src/gs/tag_text_{lang}.inc'
        if args.check:
            if path.read_text(encoding='utf-8') != output:
                raise SystemExit(f'{name} lookup is out of date; run port/tools/make_tag_text.py')
        else:
            path.write_text(output, encoding='utf-8')
        print(f'{len(rows)} {name} mod strings; format arguments preserved')


if __name__ == '__main__':
    main()
