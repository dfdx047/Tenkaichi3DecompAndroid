#!/usr/bin/env python3
"""Build the native mod's Spanish lookup; reject changed printf arguments."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
FORMAT = re.compile(r'%(?:%|[-+#0]*\d*(?:\.\d+)?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcsp])')


def catalog():
    rows = {}
    for n, line in enumerate((ROOT / 'port/translations/tag/es.tsv').read_text(encoding='utf-8').splitlines(), 1):
        if not line:
            continue
        en, es = line.split('\t')
        if not en or not es or en in rows:
            raise ValueError(f'Duplicate/empty translation at line {n}: {en}')
        if FORMAT.findall(en) != FORMAT.findall(es):
            raise ValueError(f'Format arguments changed at line {n}: {en}')
        rows[en] = es
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = catalog()
    output = '/* Generated by port/tools/make_tag_text.py. Edit port/translations/tag/es.tsv. */\n'
    for en in sorted(rows):
        output += '{' + json.dumps(en, ensure_ascii=False) + ',' + json.dumps(rows[en], ensure_ascii=False) + '},\n'
    path = ROOT / 'port/src/gs/tag_text_es.inc'
    if args.check:
        if path.read_text(encoding='utf-8') != output:
            raise SystemExit('Spanish lookup is out of date; run port/tools/make_tag_text.py')
    else:
        path.write_text(output, encoding='utf-8')
    print(f'{len(rows)} Spanish mod strings; format arguments preserved')


if __name__ == '__main__':
    main()
