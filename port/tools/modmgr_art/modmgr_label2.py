"""Writes "Mod Manager" for its main-menu plate: port/include/port_modmgr_label.h (replaces modmgr_label.py).

modmgr_label.py stitched the word from letters of other plates (the M was an upside-down W), which showed. This one
draws it with plate_label.py: Tahoma Bold, sized and coloured from "Dragon History",
in the palette of the second label sheet, as runs for its free fourth row (where the old label went).

    modmgr_label2.py      reads gamedata/pzs3us1/00449.bin; writes the header and build/modmgr_label.png
"""
import pathlib

import numpy as np
from PIL import Image
import os
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')).replace('\\', '/')  # the repository


HERE = pathlib.Path(__file__).resolve().parent
_src = (HERE / 'plate_label.py').read_text(encoding='utf-8')
_ns = {'__file__': str(HERE / 'plate_label.py'), '__name__': 'plate_label'}
exec(compile(_src, 'plate_label.py', 'exec'), _ns)
_ns['TEXT'] = 'Mod Manager'
build, ml, bpe, ROW_H = _ns['build'], _ns['ml'], _ns['bpe'], _ns['ROW_H']
OUT = pathlib.Path(ROOT + '/port/include/port_modmgr_label.h')


def main():
    d = open(ROOT + '/gamedata/pzs3us1/00449.bin', 'rb').read()
    pack = bpe.decode(d, bpe.section(d, 2))
    lines = ['/* Generated by port/build/ml/modmgr_label2.py: "Mod Manager" for a main-menu plate, as runs of palette indices',
             '   for the free fourth row of the second label sheet (len pixels of value v from column x of line y). */',
             '#ifndef PORT_LABEL_RUN', '#define PORT_LABEL_RUN',
             'typedef struct PortLabelRun { u8 y; u8 len; u8 x; u8 v; } PortLabelRun;', '#endif']
    sheet = Image.new('RGB', (512, ROW_H * 4 + 12), (40, 90, 160))
    for n, (lst, name) in enumerate(((5, 'sPortModMgrOff'), (6, 'sPortModMgrOn'))):
        idx, dpal, rgba = build(pack, lst)
        r = ml.runs(idx)
        lines.append('static const PortLabelRun %s[%d] = {' % (name, len(r)))
        for k in range(0, len(r), 8):
            lines.append('    ' + ' '.join('{%d, %d, %d, %d},' % t for t in r[k:k + 8]))
        lines.append('};')
        pic = dpal[idx].copy()
        pic[..., 3] = np.minimum(pic[..., 3].astype(np.int32) * 2, 255)
        ref = rgba[0:ROW_H].copy()
        ref[..., 3] = np.minimum(ref[..., 3].astype(np.int32) * 2, 255)
        bg = Image.new('RGBA', (512, ROW_H * 2 + 2), (40, 90, 160, 255))
        bg.alpha_composite(Image.fromarray(ref, 'RGBA'), (0, 0))
        bg.alpha_composite(Image.fromarray(pic, 'RGBA'), (0, ROW_H + 2))
        sheet.paste(bg.convert('RGB'), (0, n * (ROW_H * 2 + 6)))
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    sheet.resize((1024, sheet.size[1] * 2), Image.NEAREST).save(HERE.parent / 'modmgr_label.png')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
