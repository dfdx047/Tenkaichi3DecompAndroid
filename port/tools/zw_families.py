    ("Gohan", ["Gohan", "Saiyaman"]), ("Goku", ["Goku", "=Great Ape"]), ("Vegeta", ["Vegeta"]), ("Trunks", ["Trunks"]),
    ("Piccolo", ["=Piccolo (Early)", "=Piccolo (End)", "Nail"]), ("Piccolo Daimaoh", ["Demon King Piccolo"]),
    ("Kuririn", ["Krillin"]), ("Yamcha", ["Yamcha"]), ("Tenshinhan", ["Tien"]), ("Chaos", ["Chiaotzu"]),
    ("Mr. Satan", ["Mr Satan"]), ("Kaioshin", ["Kai"]), ("Yajirobe", ["Yajirobe"]), ("Paikuhan", ["Paikuhan"]),
