    ("Soldados", ["Soldier"]), ("Força Ginyu", ["Ginyu", "Recoome", "Burter", "Jeice", "Guldo"]), ("Freeza", ["Frieza"]), ("Rei Cold", ["King Cold"]),
    ("Soldados", ["Appule"]), ("Androides", ["Android 16", "Android 17", "=Android 18", "Android 19", "=Android 2"]),
    ("Android 13", ["Android 13"]), ("Super 17", ["Super 17"]), ("Cell", ["Cell"]), ("Babidi", ["Babidi"]), ("Dabura", ["Dabura"]),
